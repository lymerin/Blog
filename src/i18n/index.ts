const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  'zh-cn': zhCN,
  'zh-hk': zhHK,
}

export function isLocale(value: string | undefined): value is Locale {
  return LOCALES.includes(value as Locale)
}

export function getLocaleFromPath(pathname: string): Locale {
  const candidate = pathname.split('/').filter(Boolean)[0]
  return isLocale(candidate) ? candidate : 'zh-cn'
}

export function getLanguageTag(locale: Locale) {
  return locale === 'zh-hk' ? 'zh-HK' : 'zh-CN'
}

export function t(locale: Locale, key: TranslationKey) {
  return dictionaries[locale][key]
}

export function localePath(locale: Locale, pathname = '/') {
  const cleanPath = pathname.replace(/^\/(zh-cn|zh-hk)(?=\/|$)/, '').replace(/^\/+/, '')
  return cleanPath ? `/${locale}/${cleanPath}` : `/${locale}/`
}

export function getLocaleStaticPaths() {
  return LOCALES.map((locale) => ({ params: { locale }, props: { locale } }))
}
